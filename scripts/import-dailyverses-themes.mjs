/**
 * NÃO execute este arquivo no Supabase SQL Editor — é JavaScript (Node.js).
 *
 * No Supabase, execute apenas:
 *   1. scripts/bible-verses-by-theme.sql
 *   2. scripts/bible-verses-by-theme-data.sql
 *
 * Este script roda no terminal para regenerar o .sql de dados:
 *   node scripts/import-dailyverses-themes.mjs
 */

import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const BASE = 'https://dailyverses.net';
const UA = 'Mozilla/5.0 (compatible; app-igreja-import/1.0)';
const DELAY_MS = 400;

const outArg = process.argv.indexOf('--out');
const OUT_FILE =
  outArg >= 0
    ? process.argv[outArg + 1]
    : join(__dirname, 'bible-verses-by-theme-data.sql');

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

async function fetchHtml(path) {
  const url = path.startsWith('http') ? path : `${BASE}${path}`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  return res.text();
}

function decodeHtml(text) {
  return text
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .trim();
}

/** Parse "João 15:18" or "1 Coríntios 13:6-7" */
function parseReference(ref) {
  const m = ref.trim().match(/^(.+?)\s+(\d+):(\d+)(?:-(\d+))?$/);
  if (!m) return { livro: ref.trim(), capitulo: null, versiculo: null, versiculo_fim: null };
  return {
    livro: m[1].trim(),
    capitulo: parseInt(m[2], 10),
    versiculo: parseInt(m[3], 10),
    versiculo_fim: m[4] ? parseInt(m[4], 10) : null,
  };
}

function scrapeThemesIndex(html) {
  const h1 = html.indexOf('<h1');
  if (h1 < 0) throw new Error('Themes index: <h1> not found');
  const section = html.slice(h1, h1 + 25000);
  const col = section.match(/<ul class="column4">([\s\S]*?)<\/ul>/);
  if (!col) throw new Error('Themes index: <ul class="column4"> not found');

  const themes = [];
  const re = /<a href="\/pt\/([^"#?]+)"[^>]*>([^<]+)<\/a>/g;
  let m;
  while ((m = re.exec(col[1])) !== null) {
    const slug = m[1];
    const name = decodeHtml(m[2]);
    if (themes.some((t) => t.slug === slug)) continue;
    themes.push({ slug, name });
  }
  return themes;
}

function scrapeVersesFromThemePage(html, themeSlug, themeName) {
  const verses = [];
  const ulMatch = html.match(/<ul class="verses">([\s\S]*?)<\/ul>/);
  if (!ulMatch) return verses;

  const itemRe = /<li([^>]*)>([\s\S]*?)<\/li>/g;
  let im;
  while ((im = itemRe.exec(ulMatch[1])) !== null) {
    if (/\bad_unit\b/.test(im[1])) continue;
    const block = im[2];
    const textMatch = block.match(/<span[^>]*class="v2"[^>]*>([\s\S]*?)<\/span>/);
    const refMatch = block.match(/<a[^>]*class="vc"[^>]*>([\s\S]*?)<\/a>/);
    if (!textMatch || !refMatch) continue;

    const texto = decodeHtml(
      textMatch[1]
        .replace(/<br\s*\/?>/gi, ' ')
        .replace(/<[^>]+>/g, '')
        .replace(/\s+/g, ' ')
    );
    const referencia = decodeHtml(refMatch[1].replace(/<[^>]+>/g, ''));
    const parsed = parseReference(referencia);

    verses.push({
      theme_slug: themeSlug,
      theme_name: themeName,
      texto,
      referencia,
      livro: parsed.livro,
      capitulo: parsed.capitulo,
      versiculo: parsed.versiculo,
      versiculo_fim: parsed.versiculo_fim,
    });
  }
  return verses;
}

function parseExpectedVerseCount(html) {
  const m = html.match(/<title>\s*(\d+)\s+Versículos/i);
  return m ? parseInt(m[1], 10) : null;
}

async function scrapeThemeVerses(themeSlug, themeName) {
  const seen = new Set();
  const all = [];
  let page = 1;
  let expected = null;

  while (true) {
    const path = page === 1 ? `/pt/${themeSlug}` : `/pt/${themeSlug}?p=${page}`;
    const html = await fetchHtml(path);
    if (page === 1) expected = parseExpectedVerseCount(html);

    const batch = scrapeVersesFromThemePage(html, themeSlug, themeName);
    if (batch.length === 0) break;

    let added = 0;
    for (const v of batch) {
      if (seen.has(v.referencia)) continue;
      seen.add(v.referencia);
      all.push(v);
      added++;
    }

    if (added === 0) break;
    if (expected != null && all.length >= expected) break;

    page++;
    await sleep(DELAY_MS);
  }

  return all;
}

function sqlEscape(s) {
  if (s == null) return 'NULL';
  return `'${String(s).replace(/'/g, "''")}'`;
}

function generateSql(themes, allVerses) {
  const lines = [];
  lines.push('-- Generated by scripts/import-dailyverses-themes.mjs');
  lines.push('-- Source: https://dailyverses.net/pt/temas');
  lines.push(`-- Themes: ${themes.length}, Verses: ${allVerses.length}`);
  lines.push('');
  lines.push('-- Run bible-verses-by-theme.sql first to create tables.');
  lines.push('');
  lines.push('TRUNCATE bible_verses_by_theme RESTART IDENTITY CASCADE;');
  lines.push('TRUNCATE bible_themes RESTART IDENTITY CASCADE;');
  lines.push('');

  for (const t of themes) {
    lines.push(
      `INSERT INTO bible_themes (slug, name) VALUES (${sqlEscape(t.slug)}, ${sqlEscape(t.name)});`
    );
  }
  lines.push('');

  const batchSize = 50;
  for (let i = 0; i < allVerses.length; i += batchSize) {
    const batch = allVerses.slice(i, i + batchSize);
    lines.push(
      'INSERT INTO bible_verses_by_theme (theme_slug, texto, referencia, livro, capitulo, versiculo, versiculo_fim) VALUES'
    );
    const vals = batch.map(
      (v) =>
        `  (${sqlEscape(v.theme_slug)}, ${sqlEscape(v.texto)}, ${sqlEscape(v.referencia)}, ${sqlEscape(v.livro)}, ${v.capitulo ?? 'NULL'}, ${v.versiculo ?? 'NULL'}, ${v.versiculo_fim ?? 'NULL'})`
    );
    lines.push(vals.join(',\n') + ';');
    lines.push('');
  }
  return lines.join('\n');
}

async function main() {
  console.log('Fetching themes index...');
  const indexHtml = await fetchHtml('/pt/temas');
  const themes = scrapeThemesIndex(indexHtml);
  console.log(`Found ${themes.length} themes`);

  const allVerses = [];
  for (let i = 0; i < themes.length; i++) {
    const t = themes[i];
    process.stdout.write(`[${i + 1}/${themes.length}] ${t.slug}... `);
    try {
      const verses = await scrapeThemeVerses(t.slug, t.name);
      console.log(`${verses.length} verses`);
      allVerses.push(...verses);
    } catch (e) {
      console.log(`ERROR: ${e.message}`);
    }
    if (i < themes.length - 1) await sleep(DELAY_MS);
  }

  const sql = generateSql(themes, allVerses);
  writeFileSync(OUT_FILE, sql, 'utf8');
  console.log(`\nWrote ${OUT_FILE}`);
  console.log(`Total: ${themes.length} themes, ${allVerses.length} verses`);
  console.log('Para Supabase em partes: node scripts/split-bible-verses-sql.mjs');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
